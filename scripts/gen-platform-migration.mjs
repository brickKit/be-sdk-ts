#!/usr/bin/env node
// Generates platform-migrations/0001_besdk-platform.sql (the platform migration, P11.3) from the reference DDL
// in protocol/ddl, applied in name order. `--check` fails when the committed file differs (run after
// `make sync-protocol`).
//
// Left out:
//   07-authz-projection.sql  created only for components that declare `resources` (P6.12)
//                            TODO(authz projection task): a separate platform step, run when the member's
//                            assembly declares resources
//   be_bus.sql               owned by the project's database initialisation (P12.12), not a component schema
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const SKIP = new Set(["07-authz-projection.sql", "be_bus.sql"]);
const OUT = `${root}platform-migrations/0001_besdk-platform.sql`;

const pinned = readFileSync(`${root}protocol/PINNED`, "utf8").split("\n").find((l) => l.startsWith("be-protocol ")) ?? "be-protocol ?";
const files = readdirSync(`${root}protocol/ddl`).filter((f) => f.endsWith(".sql") && !SKIP.has(f)).sort();

const parts = [
  `-- GENERATED by scripts/gen-platform-migration.mjs from protocol/ddl (${pinned.trim()}); do not edit.`,
  "-- be-sdk-ts platform version 1: every besdk_* table and platform function of the reference DDL except",
  "-- 07-authz-projection.sql (only with declared resources) and be_bus.sql (database initialisation).",
  "-- Up Migration",
];
for (const f of files) {
  parts.push("", `-- ===== ${f} =====`, readFileSync(`${root}protocol/ddl/${f}`, "utf8").trimEnd());
}
const text = parts.join("\n") + "\n";

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== text) {
    console.error(`${OUT} is out of date: run node scripts/gen-platform-migration.mjs`);
    process.exit(1);
  }
  console.log("platform migration matches protocol/ddl");
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} from ${files.join(", ")}`);
}
